// BrewSession's skinny 7x12 blocky digits, ported bit-for-bit from
// src/c/digits.c. Tabular by construction — the reason the countdown
// never shimmies — and the same table drives the watch and this page.

export const DIGIT_W = 7;
export const DIGIT_H = 12;
const COLON_L = 2, COLON_R = 3;
const INK_L = 0, INK_R = 6;

const ROWS = {
  '0': [0x3E,0x7F,0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x63,0x7F,0x3E],
  '1': [0x78,0x78,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x7F,0x7F],
  '2': [0x3E,0x7F,0x03,0x03,0x03,0x7F,0x7E,0x60,0x60,0x60,0x7F,0x7F],
  '3': [0x3E,0x7F,0x03,0x03,0x03,0x1F,0x1E,0x03,0x03,0x03,0x7F,0x3E],
  '4': [0x63,0x63,0x63,0x63,0x63,0x63,0x7F,0x7F,0x03,0x03,0x03,0x03],
  '5': [0x7F,0x7F,0x60,0x60,0x60,0x7E,0x7F,0x03,0x03,0x03,0x7F,0x3E],
  '6': [0x3E,0x7F,0x60,0x60,0x60,0x7E,0x7F,0x63,0x63,0x63,0x7F,0x3E],
  '7': [0x7F,0x7F,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03],
  '8': [0x3E,0x7F,0x63,0x63,0x63,0x3E,0x3E,0x63,0x63,0x63,0x7F,0x3E],
  '9': [0x3E,0x7F,0x63,0x63,0x63,0x7F,0x3F,0x03,0x03,0x03,0x03,0x03],
  ':': [0x00,0x00,0x00,0x18,0x18,0x00,0x00,0x00,0x18,0x18,0x00,0x00],
};

const inkCols = (ch) => ch === ':' ? COLON_R - COLON_L + 1 : INK_R - INK_L + 1;

export function blockyHeight(scale) { return DIGIT_H * scale; }

export function blockyWidth(s, scale) {
  let w = 0;
  for (const ch of s) w += (inkCols(ch) + 1) * scale;
  return w - scale;   // no air after the last glyph
}

// Centered on cx by ink, same slot layout as the C helper in ui_fmt.c.
export function drawBlocky(ctx, s, cx, top, scale, color) {
  ctx.fillStyle = color;
  let x = cx - Math.floor(blockyWidth(s, scale) / 2);
  for (const ch of s) {
    const rows = ROWS[ch];
    const l = ch === ':' ? COLON_L : INK_L;
    for (let r = 0; r < DIGIT_H; r++) {
      const row = rows[r];
      let c = 0;
      while (c < DIGIT_W) {
        if (row & (1 << (DIGIT_W - 1 - c))) {
          let run = 0;
          while (c + run < DIGIT_W && (row & (1 << (DIGIT_W - 1 - c - run)))) run++;
          ctx.fillRect(x + (c - l) * scale, top + r * scale, run * scale, scale);
          c += run;
        } else c++;
      }
    }
    x += (inkCols(ch) + 1) * scale;
  }
}
