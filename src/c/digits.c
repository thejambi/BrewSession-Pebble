// BrewSession's skinny 8x13 digit set — see digits.h. The drawing routine
// is Emberline's, unchanged.
#include "digits.h"

const uint16_t DIGIT_ROWS[11][DIGIT_H] = {
  { 0x7E, 0xFF, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0x7E },   // 0
  { 0xF8, 0xF8, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18, 0xFF, 0xFF },   // 1
  { 0x7E, 0xFF, 0x03, 0x03, 0x03, 0xFF, 0xFE, 0xC0, 0xC0, 0xC0, 0xC0, 0xFF, 0xFF },   // 2
  { 0x7E, 0xFF, 0x03, 0x03, 0x03, 0x3F, 0x3E, 0x03, 0x03, 0x03, 0x03, 0xFF, 0x7E },   // 3
  { 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0xFF, 0x03, 0x03, 0x03, 0x03, 0x03 },   // 4
  { 0xFF, 0xFF, 0xC0, 0xC0, 0xC0, 0xFE, 0xFF, 0x03, 0x03, 0x03, 0x03, 0xFF, 0x7E },   // 5
  { 0x7E, 0xFF, 0xC0, 0xC0, 0xC0, 0xFE, 0xFF, 0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0x7E },   // 6
  { 0xFF, 0xFF, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03 },   // 7
  { 0x7E, 0xFF, 0xC3, 0xC3, 0xC3, 0x7E, 0x7E, 0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0x7E },   // 8
  { 0x7E, 0xFF, 0xC3, 0xC3, 0xC3, 0xFF, 0x7F, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03 },   // 9
  { 0x00, 0x00, 0x00, 0x18, 0x18, 0x00, 0x00, 0x00, 0x18, 0x18, 0x00, 0x00, 0x00 },   // :
};

void digit_draw(GContext *ctx, int idx, int x, int top, int scale) {
  for (int r = 0; r < DIGIT_H; r++) {
    uint16_t row = DIGIT_ROWS[idx][r];
    int c = 0;
    while (c < DIGIT_W) {
      if (row & (1 << (DIGIT_W - 1 - c))) {
        int run = 0;
        while (c + run < DIGIT_W &&
               (row & (1 << (DIGIT_W - 1 - c - run)))) run++;
        graphics_fill_rect(ctx, GRect(x + c * scale, top + r * scale,
                                      run * scale, scale), 0,
                           GCornerNone);
        c += run;
      } else {
        c++;
      }
    }
  }
}
